/// lucide-react 1.14.0's drawings of the icons the catalog draws
/// differently: `(catalog name, SVG)`, sorted by name.
pub use lucide_1_14::DRAWINGS as REACT_DRAWINGS;

/// The vendored lucide-react drawing for an icon path (`icons/zap.svg`),
/// when the catalog's differs.
pub fn react_drawing(path: &str) -> Option<&'static [u8]> {
    let name = path.strip_prefix("icons/")?.strip_suffix(".svg")?;
    REACT_DRAWINGS
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .map(|i| REACT_DRAWINGS[i].1)
}

/// The catalog's own SVG for a path (Lucide 1.43.0, without the vendored
/// drawings): the React UI's icons, then gpui-kit-assets' default bundle.
pub fn catalog_drawing(path: &str) -> Result<Option<Cow<'static, [u8]>>> {
    match ReactIcons.load(path)? {
        Some(svg) => Ok(Some(svg)),
        None => Assets.load(path),
    }
}

/// The app's asset source: the vendored lucide-react drawings
/// ([`REACT_DRAWINGS`]), then the React UI's icons from the catalog, then
/// gpui-kit-assets' default bundle (the icons gpui-component draws itself).
#[derive(Clone, Copy, Debug, Default)]
pub struct IconAssets;

impl AssetSource for IconAssets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        match react_drawing(path) {
            Some(svg) => Ok(Some(Cow::Borrowed(svg))),
            None => catalog_drawing(path),
        }
    }

    fn list(&self, path: &str) -> Result<Vec<SharedString>> {
        let mut paths = ReactIcons.list(path)?;
        paths.extend(Assets.list(path)?);
        paths.sort();
        paths.dedup();
        Ok(paths)
    }
}

/// The GPUI Kit icon for a lucide-react import name (`"Loader2"`).
pub fn icon(react_name: &str) -> Option<IconName> {
    ICONS
        .binary_search_by(|(name, _)| name.cmp(&react_name))
        .ok()
        .map(|i| ICONS[i].1)
}
