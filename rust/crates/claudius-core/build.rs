//! Embed the TS app's SQLite migrations (`lib/server/db-migrations/NNN_*.sql`)
//! so the Rust and TS backends share ONE schema source of truth. Adding a new
//! numbered file there is picked up by both on the next build.

use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = manifest.join("../../../lib/server/db-migrations");
    let dir = dir.canonicalize().unwrap_or(dir);
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut entries: Vec<(u32, PathBuf)> = std::fs::read_dir(&dir)
        .map(|rd| {
            rd.filter_map(Result::ok)
                .filter_map(|e| {
                    let name = e.file_name().to_string_lossy().into_owned();
                    if !name.ends_with(".sql") {
                        return None;
                    }
                    let digits: String = name.chars().take_while(char::is_ascii_digit).collect();
                    if digits.is_empty() || !name[digits.len()..].starts_with('_') {
                        return None;
                    }
                    Some((digits.parse().ok()?, e.path()))
                })
                .collect()
        })
        .unwrap_or_default();
    entries.sort_by_key(|(id, _)| *id);

    let mut src = String::from(
        "/// `(id, sql)` pairs, ascending. Generated by build.rs.\npub static MIGRATIONS: &[(u32, &str)] = &[\n",
    );
    for (id, path) in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
        src.push_str(&format!(
            "    ({id}, include_str!({:?})),\n",
            path.display().to_string()
        ));
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("migrations.rs");
    std::fs::write(out, src).unwrap();
}
